EXPECTED_INVENTORY = 145

_ROW_RE = re.compile(r"\|\s*`((?:napi_|node_api_)[A-Za-z0-9_]+)`\s*\|")


def repo_root() -> Path:
    return Path(__file__).resolve().parent.parent.parent


def parse_inventory(path: Path) -> list:
    """Return the 145 inventory symbols (Inventory section only).

    The inventory has two tables: Inventory (145) then Excluded.
    Only rows before the Excluded header count; excluded v9/v10/
    experimental symbols must never enter the exports file.
    """
    text = path.read_text()
    inventory_part = text.split("## Excluded")[0]
    # Rows look like: | `napi_x` | `header` | Group |
    # Split each line on | and take the first cell's backticked name.
    syms = []
    for line in inventory_part.splitlines():
        if line.strip().startswith("| `"):
            first = line.split("|")[1].strip()
            m = re.match(r"`((?:napi_|node_api_)[A-Za-z0-9_]+)`", first)
            if m:
                syms.append(m.group(1))
    return syms


def render(landed, host) -> str:
    exports = sorted(set(landed) | set(host))
    lines = [
        "# libChakraNodeApi exports (generated) -- do not edit by hand.",
        "# Regenerate: python3 tools/build/gen_nodeapi_exports.py",
        "# Sources: doc/node-api-inventory.md (145 at NAPI_VERSION=8)",
        "#   + private host API (plan §3.2): chakra_nodeapi_create_env /",
        f"#     chakra_nodeapi_destroy_env plus 3 N4.1 pending-module helpers.",
        f"# Full coverage: {len(landed)} napi_* + {len(host)} host = {len(exports)} symbols.",
        "# Format: one symbol per line, plain C name (no Mach-O leading",
        "# underscore). check-nodeapi compares nm -gU T symbols,",
        "# normalized by stripping one leading underscore on Mach-O.",
        "",
    ]
    lines.extend(exports)
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if nodeapi_exports.txt is stale")
    ap.add_argument("--root", type=Path, default=None)
    args = ap.parse_args()
    root = args.root.resolve() if args.root else repo_root()
    inventory = root / "doc" / "node-api-inventory.md"
    exports_path = root / "tools" / "build" / "nodeapi_exports.txt"

    syms = parse_inventory(inventory)
    print(f"inventory: {len(syms)} symbols (expected {EXPECTED_INVENTORY})")
    if len(syms) != EXPECTED_INVENTORY:
        print(f"error: inventory count {len(syms)} != {EXPECTED_INVENTORY}; "
              f"investigate, do not relax the generator", file=sys.stderr)
        return 1
    if len(set(syms)) != len(syms):
        print("error: duplicate symbols in inventory", file=sys.stderr)
        return 1
    missing = [s for s in WAVE1_LANDED if s not in syms]
    if missing:
        print(f"error: landed symbols not in inventory: {sorted(missing)}",
              file=sys.stderr)
        return 1
    expected = render(WAVE1_LANDED, HOST_API)
    exports = sorted(set(WAVE1_LANDED) | set(HOST_API))
    print(f"exports: {len(exports)} symbols "
          f"({len(WAVE1_LANDED)} napi + {len(HOST_API)} host)")

    if args.check:
        if not exports_path.exists():
            print(f"error: missing {exports_path}", file=sys.stderr)
            return 1
        actual = exports_path.read_text()
        if actual != expected:
            print("error: nodeapi_exports.txt differs from generation; "
                  "regenerate with `python3 tools/build/gen_nodeapi_exports.py`",
                  file=sys.stderr)
            return 1
        print("check ok: nodeapi_exports.txt matches generation")
        return 0
    exports_path.parent.mkdir(parents=True, exist_ok=True)
    exports_path.write_text(expected)
    print(f"wrote {exports_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
