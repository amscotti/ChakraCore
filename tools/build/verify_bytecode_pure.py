"""Run regenByteCode.py --verify as a pure check.

regenByteCode.py --verify REWRITES the checked-in bytecode headers even
when the verdict is green (fresh mtimes on identical bytes), and on a
red verdict it leaves the regenerated bytes behind — a second run then
passes, self-healing red-to-green and masking staleness. This wrapper
copies the script and its InJavascript inputs into a private scratch tree
and runs the existing verifier there with the built shell. Source headers
are never overwritten, including during failures, interrupts or concurrent
checks. The wrapper returns the script's verdict.

Usage: verify_bytecode_pure.py <regenByteCode.py> [regen args...]
Requires --verify and --binary=<built ch>: this is a check of an existing
engine, not a legacy build or a bytecode-regeneration entry point.
Header paths are derived from the regen script's own location
(<root>/tools/regenByteCode.py -> <root>/lib/Runtime/Library/
InJavascript/JsBuiltIn.*.h), so the wrapper also works against a
scratch copy of the tree.
"""

import os
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common


def main(argv):
    if len(argv) < 2:
        print("usage: verify_bytecode_pure.py <regenByteCode.py> [regen args...]",
              file=sys.stderr)
        return 2
    regen = os.path.abspath(argv[1])
    rest = list(argv[2:])
    if "--verify" not in rest:
        print("verify_bytecode_pure: refusing to run without --verify "
              "(regenerating modes intentionally write new bytes)",
              file=sys.stderr)
        return 2
    binary_args = [i for i, arg in enumerate(rest) if arg.startswith("--binary=")]
    if len(binary_args) != 1 or not rest[binary_args[0]][len("--binary="):]:
        print("verify_bytecode_pure: requires --binary=<built ch>", file=sys.stderr)
        return 2
    i = binary_args[0]
    rest[i] = "--binary=" + os.path.abspath(rest[i][len("--binary="):])
    js_dir = os.path.join(os.path.dirname(os.path.dirname(regen)),
                          "lib", "Runtime", "Library", "InJavascript")
    try:
        with tempfile.TemporaryDirectory(prefix="verify-bytecode-") as tmp:
            tools = os.path.join(tmp, "tools")
            os.makedirs(tools)
            scratch_regen = os.path.join(tools, "regenByteCode.py")
            shutil.copyfile(regen, scratch_regen)
            # Copy the small input directory, not the checkout/build outputs.
            # copytree copies symlink targets too: regenerated outputs cannot
            # reach the original headers through a retained symlink.
            scratch_js = os.path.join(tmp, "lib", "Runtime", "Library", "InJavascript")
            shutil.copytree(js_dir, scratch_js)
            rc, _ = common.run_tee([sys.executable, scratch_regen] + rest, cwd=tmp)
    except subprocess.TimeoutExpired:
        print("verify_bytecode_pure: FAIL: verifier timed out", file=sys.stderr)
        return 1
    except OSError as e:
        print("verify_bytecode_pure: FAIL: %s" % e, file=sys.stderr)
        return 1
    print("verify_bytecode_pure: source headers unchanged; regen exit %d" % rc)
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv))
