"""Run regenByteCode.py --verify as a pure check.

regenByteCode.py --verify REWRITES the checked-in bytecode headers even
when the verdict is green (fresh mtimes on identical bytes), and on a
red verdict it leaves the regenerated bytes behind — a second run then
passes, self-healing red-to-green and masking staleness. This wrapper
snapshots the headers (bytes + mtimes), runs the script, restores every
header byte- and mtime-identical, and exits with the script's verdict.

Usage: verify_bytecode_pure.py <regenByteCode.py> [regen args...]
Requires --verify in the regen args: regenerating modes intentionally
write new bytes (plus a fresh GUID), which this wrapper must never run.
Header paths are derived from the regen script's own location
(<root>/tools/regenByteCode.py -> <root>/lib/Runtime/Library/
InJavascript/JsBuiltIn.*.h), so the wrapper also works against a
scratch copy of the tree.
"""

import os
import subprocess
import sys

HEADERS = (
    "JsBuiltIn.nojit.bc.64b.h",
    "JsBuiltIn.nojit.bc.32b.h",
    "JsBuiltIn.bc.64b.h",
    "JsBuiltIn.bc.32b.h",
)


def main(argv):
    if len(argv) < 2:
        print("usage: verify_bytecode_pure.py <regenByteCode.py> [regen args...]",
              file=sys.stderr)
        return 2
    regen = os.path.abspath(argv[1])
    rest = argv[2:]
    if "--verify" not in rest:
        print("verify_bytecode_pure: refusing to run without --verify "
              "(regenerating modes intentionally write new bytes)",
              file=sys.stderr)
        return 2
    js_dir = os.path.join(os.path.dirname(os.path.dirname(regen)),
                           "lib", "Runtime", "Library", "InJavascript")
    snapshots = {}
    for name in HEADERS:
        path = os.path.join(js_dir, name)
        if not os.path.isfile(path):
            continue
        with open(path, "rb") as f:
            data = f.read()
        st = os.stat(path)
        snapshots[path] = (data, (st.st_atime_ns, st.st_mtime_ns))

    proc = subprocess.run([sys.executable, regen] + rest)

    restored = 0
    for path, (data, times) in snapshots.items():
        try:
            with open(path, "rb") as f:
                current = f.read()
        except OSError:
            current = None
        if current != data:
            with open(path, "wb") as f:
                f.write(data)
        os.utime(path, ns=times)
        restored += 1
    print("verify_bytecode_pure: %d header(s) restored byte- and "
          "mtime-identical; regen exit %d" % (restored, proc.returncode))
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv))
