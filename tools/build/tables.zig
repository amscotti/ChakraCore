//! B2.2: contract tables for the full Mac compile+link graph.
//!
//! Source lists transcribe doc/build-contract-mac.md section 4 in CMakeLists
//! listing order; include spellings are the exact observed strings from the
//! reference compile DB (including `..` segments — string-faithful, so the
//! generated command lines diff cleanly against the reference).
//!
//! String-fidelity caveat: `-DChakraCore_EXPORTS`/`-DGCStress_EXPORTS` are
//! emitted last (via `target_define`) while the reference DEFINES lists
//! them 3rd/6th (alphabetical among the defines, build.ninja); `-Dch_EXPORTS`
//! is last on both sides. Position is semantically nil (independent -D flags).

pub const Pic = enum { pic, pie, none };

pub const Group = struct {
    cxx: []const []const u8 = &.{},
    c: []const []const u8 = &.{},
    asm_files: []const []const u8 = &.{},
    /// Group-specific `-I` dirs (relative), in observed order, after the
    /// global dirs + ICU and before `-isystem /usr/local/include`.
    extra_includes: []const []const u8 = &.{},
    target_define: ?[]const u8 = null,
    pic: Pic = .pic,
    pal: bool = false,
    /// Singular-archive name (contract section 5.3): when set, build.zig
    /// archives this group's objects into `lib<name>.a` in a loop, instead
    /// of one stanza per archive. Only the three contract groups set this.
    singular_name: ?[]const u8 = null,
};

