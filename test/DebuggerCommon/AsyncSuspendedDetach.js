// A plain async function suspended at an await and a generator suspended at a
// yield must both survive a dynamic attach *and* a detach while they are still
// suspended. The async frame resumes on its original (retained) body, the
// generator completes with a proper iterator result, and a second async
// invocation runs on the fresh debug body. See doc/dbg-async-attach.md and
// doc/b4-swarm-handoff.md D1.

var resolveAwait;
var pending = new Promise(function (r) { resolveAwait = r; });

async function suspended() {
    WScript.Echo("async before");
    var v = await pending;
    WScript.Echo("async after " + v);
}

function* iterator() {
    WScript.Echo("gen before");
    yield 1;
    WScript.Echo("gen after");
}

suspended();
var it = iterator();
var first = it.next();
WScript.Echo("gen first done=" + first.done + " value=" + first.value);

// A suspended generator that becomes unreachable must release its retained
// FunctionBody through JavascriptGenerator::Finalize. The finalizer is the
// release half of the reparse guard and the reason the guard is tied to the
// write-barrier build; this path is otherwise unobservable from script.
function* droppedIterator() {
    yield 1;
}
(function () {
    var dropped = droppedIterator();
    dropped.next();
    dropped = null;
})();
CollectGarbage();
CollectGarbage();
WScript.Echo("collected");

WScript.Attach(function () {
    // The pre-attach invocation is still suspended; this new invocation must
    // execute on the debug bytecode generated by the attach reparse.
    suspended();

    WScript.Detach(function () {
        WScript.Echo("detached");

        // The generator frame was suspended across both the attach and the
        // detach reparses and must complete with an iterator result, not a
        // bare undefined.
        var second = it.next();
        WScript.Echo("gen second done=" + second.done + " value=" + second.value);

        resolveAwait(41);
    });
});

WScript.Echo("done");
